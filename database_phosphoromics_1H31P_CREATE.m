% Database organization
% ---------------------
% Each metabolite is stored as one field of simDB. The field name is set by
% the variable "metabolite", and the associated structure contains the spin
% topology, relaxation parameters, isotope composition, and optional
% simulation-partitioning information.
%
% Main fields used in each database entry
% ---------------------------------------
% w_CS_J:
%   Upper-triangular spin-system matrix following the GISSMO-style
%   convention used by the simulation code.
%   - Diagonal elements contain chemical shifts in ppm.
%   - Off-diagonal elements contain scalar J couplings in Hz.
%   - Zero entries indicate that no coupling is included between the
%     corresponding spins.
%
% T1 and T2:
%   Longitudinal and transverse relaxation times for each explicitly
%   represented spin. The number and ordering of values must match the
%   spin ordering in w_CS_J.
%
% Isotopes:
%   Ordered list of isotope types present in the entry, for example
%   ["1H","31P"] or ["1H","14N","31P"].
%
% IsotopeCount:
%   Number of explicitly represented spins belonging to each isotope in
%   Isotopes. The counts should sum to the dimension of w_CS_J.
%
% block_sizes:
%   Optional partition of the full spin system into smaller simulation
%   blocks. This is used for large systems when the simulation workflow
%   treats non-connected groups separately. Only for 1H!
%
% base_level and space_level:
%   Optional simulation settings retained for compatibility with the
%   downstream SPINACH workflow.
%
% Pivot:
%   Optional,Pivot identifies the spin site used as the reference when applicable.
%
% notes:
%   Human-readable label for the database entry; here it is normally set
%   equal to the metabolite field name.
%
% Important maintenance notes
% ---------------------------
% 1. Keep the ordering of w_CS_J, T1/T2, Isotopes, and IsotopeCount
%    mutually consistent.
% 2. The script saves simDB with the "-struct" option, so each metabolite
%    becomes a top-level variable in the MAT-file rather than simDB being
%    saved as a single enclosing structure.


%Creates a database with entries as topological matrices following the
